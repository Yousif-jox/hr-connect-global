/** All job ids in data order. */
export const JOB_IDS: string[] = jobs.en.map((j) => j.id);

/** Distinct departments in data order (localised). */
export const jobDepartments = (lang: JobLang): string[] => [...new Set(jobs[lang].map((j) => j.dept))];

/**
 * Distinct office cities, derived from the `loc` field. Only roles tied to a
 * physical office contribute a city (fully remote roles are counted separately).
 */
export const jobCities = (lang: JobLang): string[] =>
  [...new Set(jobs[lang].filter((j) => j.loc.includes(" · ")).map((j) => j.loc.split(" · ")[0]!))].sort(
    (a, b) => a.localeCompare(b, lang),
  );

/** How many roles are fully remote (no office attached). */
export const remoteRoleCount = (lang: JobLang): number =>
  jobs[lang].filter((j) => !j.loc.includes(" · ")).length;

/** Single job lookup by id. */
export const findJob = (lang: JobLang, id: string): Job | undefined => jobs[lang].find((j) => j.id === id);

/**
 * Up to `limit` other roles to suggest next: same department first,
 * topped up with the most recent roles from the rest of the portfolio.
 */
export function relatedJobs(lang: JobLang, id: string, limit = 3): Job[] {
  const pool = jobs[lang];
  const current = pool.find((j) => j.id === id);
  if (!current) return pool.slice(0, limit);
  const sameDepartment = pool.filter((j) => j.id !== id && j.dept === current.dept);
  const rest = pool.filter((j) => j.id !== id && j.dept !== current.dept);
  return [...sameDepartment, ...rest].slice(0, limit);
}
